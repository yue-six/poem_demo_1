-- 5. 更新朝代统计视图
CREATE OR REPLACE VIEW dynasty_categories AS
SELECT 
  d.name as dynasty,
  d.period,
  COUNT(p.id) as poem_count,
  COUNT(DISTINCT p.poet_id) as poet_count,
  COALESCE(AVG(p.likes), 0) as avg_likes
FROM dynasties d
LEFT JOIN poems p ON p.dynasty = d.name
GROUP BY d.id, d.name, d.period
ORDER BY d.id;

